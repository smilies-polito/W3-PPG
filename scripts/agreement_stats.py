"""
Evaluate agreement between the HR measurements obtained from the Persimmon device,
Polar and Shimmer using the window-level dataset generated by
compute_windows.py.

The script computes pairwise agreement metrics for each device pair
and intraclass correlation across all three devices.

Pairwise metrics:
    - Mean absolute error (MAE)
    - Root mean square error (RMSE)
    - Mean bias
    - Bland-Altman 95% limits of agreement
    - Pearson correlation coefficient (r)
    - Percentage of windows within 5 and 10 bpm
    - Mean absolute percentage error (MAPE)
    - Lin's concordance correlation coefficient (CCC)

Three-device agreement:
    - Intraclass correlation coefficient, ICC(A,1), using a
      two-way model with single measurements and absolute agreement.

Statistical analysis:
    - Metrics are computed using available paired observations.
    - Three-device ICC is computed using complete observations
      across all three devices.
    - Results are reported for the complete dataset and separately
      for each annotated activity.
    - 95% confidence intervals are estimated using a participant-level
      cluster bootstrap (percentile method), accounting for the
      dependence between windows from the same recording/participant.

Usage:
    python agreement_stats.py

    python agreement_stats.py --windows <input_file> --out-dir <output_folder>
                              [--bootstrap <n_resamples>] [--seed <random_seed>]

Input:
    Window-level HR table produced by compute_windows.py.

Output:
    agreement_overall.csv:
        Agreement metrics and 95% confidence intervals across all
        available labelled and unlabelled windows.

    agreement_by_activity.csv:
        Agreement metrics and 95% confidence intervals for each
        annotated activity.

Output directories, bootstrap settings and default paths are defined
in config.py.
"""

