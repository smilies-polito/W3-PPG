from pathlib import Path
sys.path.insert(0, str(Path(__file__).resolve().parent))   # work from any current folder
import numpy as np, pandas as pd
import config

PAIRS = [('persimmon', 'polar', 'Persimmon-Polar'), ('persimmon', 'shimmer', 'Persimmon-Shimmer'), ('polar', 'shimmer', 'Polar-Shimmer')]
ALL3 = ['persimmon', 'polar', 'shimmer']

def ccc(x, y):
    """
    Compute Lin's concordance correlation coefficient (CCC).

    Measures agreement between two continuous variables by combining
    Pearson correlation and deviation from the identity line.

    Args:
        x (array-like): Measurements from the first device.
        y (array-like): Measurements from the second device.

    Returns:
        float: Lin's CCC. Returns NaN if the denominator is zero.
    """

    x, y = np.asarray(x, float), np.asarray(y, float)
    den = x.var() + y.var() + (x.mean() - y.mean()) ** 2
    return 2 * np.cov(x, y, bias=True)[0, 1] / den if den > 0 else np.nan

def icc_a1(M):
    """
    Compute the intraclass correlation coefficient ICC(A,1).

    Estimates absolute agreement among multiple measurement methods
    using a two-way model with single measurements.

    Args:
        M (numpy.ndarray): Matrix of measurements with shape
            (n_subjects, n_devices). Rows represent subjects and
            columns represent measurement devices.

    Returns:
        float: ICC(A,1) estimate.
    """

    n, k = M.shape; gm = M.mean(); rm = M.mean(1); cm = M.mean(0)
    bms = k * ((rm - gm) ** 2).sum() / (n - 1); jms = n * ((cm - gm) ** 2).sum() / (k - 1)
    ems = ((M - rm[:, None] - cm[None, :] + gm) ** 2).sum() / ((n - 1) * (k - 1))
    return (bms - ems) / (bms + (k - 1) * ems + k * (jms - ems) / n)

def pair_metrics(a, b):
    """
    Compute pairwise agreement metrics between two devices.

    Calculates error, bias, correlation and concordance measures,
    together with Bland-Altman limits of agreement and the percentage
    of observations within predefined HR difference thresholds.

    Args:
        a (array-like): HR estimates from the first device (bpm).
        b (array-like): HR estimates from the reference/comparison device (bpm).

    Returns:
        dict: Dictionary containing MAE, RMSE, bias, Bland-Altman
            limits of agreement, Pearson r, percentages within
            5 and 10 bpm, MAPE, and Lin's CCC.
    """
    
    a, b = np.asarray(a, float), np.asarray(b, float)
    d = a - b; sd = d.std(ddof=1)

    return dict(MAE=np.abs(d).mean(), RMSE=np.sqrt((d ** 2).mean()), bias=d.mean(),
                LoA_lo=d.mean() - 1.96 * sd, LoA_hi=d.mean() + 1.96 * sd,
                r=np.corrcoef(a, b)[0, 1],
                within5=100 * (np.abs(d) <= 5).mean(), within10=100 * (np.abs(d) <= 10).mean(),
                MAPE=100 * (np.abs(d) / b).mean(),
                CCC=ccc(a, b))

def bootstrap(df, fn, B, rng):
    """
    Participant-level cluster bootstrap.

    Resamples whole recordings (participants) with replacement, keeping
    all windows of a participant together, and applies `fn` to each
    resampled dataset.

    Args:
        df (pandas.DataFrame): Window-level dataset with a 'recording'
            column identifying the participant.
        fn (callable): Function that takes a resampled DataFrame and
            returns the statistic of interest, or None if it cannot be
            computed.
        B (int): Number of bootstrap resamples.
        rng (numpy.random.Generator): Random number generator.

    Returns:
        list: Statistics from the resamples where `fn` did not return
            None. It can be shorter than B.
    """
    
    groups = {k: g for k, g in df.groupby('recording')}; ids = np.array(list(groups)); out = []
    for _ in range(B):
        r = fn(pd.concat([groups[i] for i in rng.choice(ids, len(ids))]))
        if r is not None: out.append(r)
    return out

def analyse(W, scope, B, rng):
    """
    Compute agreement statistics for one subset of windows.

    For each device pair (Persimmon-Polar, Persimmon-Shimmer,
    Polar-Shimmer) the metrics of `pair_metrics` are computed on the
    windows where both devices have an estimate. For the three devices
    together, ICC(A,1) is computed on the windows where all three have
    an estimate. 95% confidence intervals come from a participant-level
    cluster bootstrap (percentile method). The limits of agreement
    (LoA_lo, LoA_hi) are returned without confidence intervals.

    A comparison is skipped when fewer than 3 participants or fewer than
    5 windows are available.

    Args:
        W (pandas.DataFrame): Window-level table (windows.csv) with
            columns 'recording' (participant) and 'persimmon', 'polar'
            and 'shimmer' (HR in bpm; NaN where the device has no
            estimate).
        scope (str): Label stored in the 'scope' column of the output,
            e.g. 'all windows' or an activity name.
        B (int): Number of bootstrap resamples.
        rng (numpy.random.Generator): Random number generator used by
            the bootstrap.

    Returns:
        list of dict: One row per comparison, with scope, comparison,
            windows, participants, the metrics, and their confidence
            limits (<metric>_lo, <metric>_hi). The last row, when
            present, holds ICC with ICC_lo and ICC_hi.
    """
    rows = []
    for a, b, name in PAIRS:
        m = W.dropna(subset=[a, b])
        if m['recording'].nunique() < 3 or len(m) < 5: continue
        est = pair_metrics(m[a].values, m[b].values)
        bs = pd.DataFrame(bootstrap(m, lambda d: pair_metrics(d[a].values, d[b].values), B, rng))
        row = dict(scope=scope, comparison=name, windows=len(m), participants=m.recording.nunique())
        for k, v in est.items():
            row[k] = v
            if not k.startswith('LoA'): row[k + '_lo'], row[k + '_hi'] = np.nanpercentile(bs[k], [2.5, 97.5])
        rows.append(row)
    m = W.dropna(subset=ALL3)
    if m.recording.nunique() >= 3 and len(m) >= 5:
        f = lambda d: icc_a1(d[ALL3].values); bs = bootstrap(m, f, B, rng)
        rows.append(dict(scope=scope, comparison='All three (ICC)', windows=len(m), participants=m.recording.nunique(),
                         ICC=f(m), ICC_lo=np.nanpercentile(bs, 2.5), ICC_hi=np.nanpercentile(bs, 97.5)))
    return rows

def main(windows=None, out_dir=None, bootstrap=None, seed=None):
    """
    Compute the agreement statistics and save them as CSV files.

    Reads the window-level table, computes the statistics on all
    windows and separately for each activity label (windows labelled
    'unlabelled' are left out of the per-activity analysis), writes
    two tables and prints the overall results. Any argument left as
    None takes its default from config.py.

    Args:
        windows (str or Path, optional): Window-level table produced by
            compute_windows.py. Default: windows.csv in config.OUT_DIR.
        out_dir (str or Path, optional): Folder for the output files.
            Default: config.OUT_DIR.
        bootstrap (int, optional): Number of bootstrap resamples.
            Default: config.BOOTSTRAP.
        seed (int, optional): Random seed of the bootstrap.
            Default: config.SEED.

    Returns:
        tuple: (overall, by_activity), two pandas DataFrames with the
            overall results and the per-activity results.

    Outputs:
        agreement_overall.csv and agreement_by_activity.csv in out_dir.

    Raises:
        SystemExit: If the window-level table is not found.
    """
    windows = os.fspath(windows or os.path.join(config.OUT_DIR, 'windows.csv')); out_dir = os.fspath(out_dir or config.OUT_DIR)
    bootstrap = bootstrap or config.BOOTSTRAP; seed = config.SEED if seed is None else seed
    if not os.path.exists(windows): raise SystemExit(f'{windows} not found: run compute_windows.py first (or give --windows).')
    W = pd.read_csv(windows); os.makedirs(out_dir, exist_ok=True); rng = np.random.default_rng(seed)
    overall = pd.DataFrame(analyse(W, 'all windows', bootstrap, rng)); overall.to_csv(os.path.join(out_dir, 'agreement_overall.csv'), index=False)
    by = []
    for act in W.activity.unique():
        if act == 'unlabelled': continue
        by += analyse(W[W.activity == act], act, bootstrap, rng)
    pd.DataFrame(by).to_csv(os.path.join(out_dir, 'agreement_by_activity.csv'), index=False)
    pd.set_option('display.width', 200)
    print(overall[['comparison', 'windows', 'participants', 'MAE', 'CCC', 'ICC']].round(3).to_string(index=False))
    return overall, pd.DataFrame(by)

