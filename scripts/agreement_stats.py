    ap = argparse.ArgumentParser(
        description="Agreement statistics between devices (MAE, RMSE, bias, limits of agreement, Pearson r, % within 5/10 bpm, MAPE, "
                    "Lin's CCC per device pair; ICC(A,1) for the three devices), overall and per activity, with participant-level "
                    "cluster-bootstrap 95% CIs. All options are optional: the defaults are set in config.py.")
    ap.add_argument('--windows', help='Window-level table produced by compute_windows.py. Default: results/windows.csv.')
    ap.add_argument('--out-dir', help='Folder where agreement_overall.csv and agreement_by_activity.csv are saved. Default: results/.')
    ap.add_argument('--bootstrap', type=int, help='Number of bootstrap resamples for the confidence intervals. Default: BOOTSTRAP in config.py (1000).')
    ap.add_argument('--seed', type=int, help='Random seed of the bootstrap, for reproducible intervals. Default: SEED in config.py (7).')
    a = ap.parse_known_args()[0]          # unknown arguments (injected by some IDEs / notebooks) are ignored
    main(a.windows, a.out_dir, a.bootstrap, a.seed)
