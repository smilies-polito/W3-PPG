"""
Validate the statistical functions implemented in agreement_stats.py
against independent reference implementations.

The script cross-checks the following metrics:

    - Intraclass correlation coefficient ICC(A,1), against
      pingouin.intraclass_corr (optional dependency).
    - Lin's concordance correlation coefficient (CCC), against
      an independent implementation based on Lin's formula.
    - Pearson correlation coefficient (r), against scipy.stats.pearsonr.

Validation details:
    - CCC and Pearson r are checked for each pair of devices.
    - ICC(A,1) is checked using complete observations from all three
      devices.
    - Numerical differences are evaluated against predefined
      tolerances.
    - Only the ICC point estimate is compared. Pingouin's parametric
      confidence interval assumes independent observations and is
      therefore not used; confidence intervals in the main analysis
      are obtained through participant-level cluster bootstrap.

Usage:
    python check_statistics.py

Input:
    Window-level HR table generated by compute_windows.py.

Output:
    Validation results are printed to the console.
    The script exits with status 0 if all available checks pass,
    or status 1 if any check fails.

The input path and default settings are defined in config.py.
Pingouin is an optional dependency and can be installed using:
    pip install pingouin
"""

