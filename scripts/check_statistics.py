import os, sys
from pathlib import Path
sys.path.insert(0, str(Path(__file__).resolve().parent))
import numpy as np, pandas as pd
from scipy.stats import pearsonr
import config, agreement_stats as A

def main(windows=None, tol_icc=1e-3, tol_ccc=1e-9):
    """
    Cross-check the agreement statistics against independent implementations (pingouin, scipy).

    Loads the window-level HR dataset and compares the CCC, Pearson
    correlation and ICC(A,1) estimates against independent reference
    calculations.

    Args:
        windows (str, optional): Path to the window-level HR CSV file.
            Defaults to windows.csv in config.OUT_DIR.
        tol_icc (float, optional): Maximum absolute difference allowed
            between the two ICC estimates. Defaults to 1e-3.
        tol_ccc (float, optional): Maximum absolute difference allowed
            for the CCC and Pearson correlation comparisons.
            Defaults to 1e-9.

    Returns:
        int: Exit status (0 if all available checks pass, 1 otherwise).
    """

    windows = os.fspath(windows or os.path.join(config.OUT_DIR, 'windows.csv'))
    if not os.path.exists(windows): sys.exit(f'{windows} not found: run compute_windows.py first.')
    W = pd.read_csv(windows); ok = True
    for a, b, name in A.PAIRS:                                           # CCC and Pearson r, pairwise
        m = W.dropna(subset=[a, b]); x, y = m[a].values, m[b].values
        r = np.corrcoef(x, y)[0, 1]
        ref = 2 * r * x.std() * y.std() / (x.var() + y.var() + (x.mean() - y.mean()) ** 2)    # Lin (1989), population variances
        d_ccc = abs(A.ccc(x, y) - ref); d_r = abs(A.pair_metrics(x, y)['r'] - pearsonr(x, y)[0])
        good = d_ccc < tol_ccc and d_r < tol_ccc; ok &= good
        print(f'{name:18s} CCC {A.ccc(x, y):.4f} (reference {ref:.4f})  r {A.pair_metrics(x, y)["r"]:.4f}  -> {"OK" if good else "MISMATCH"}')
    m = W.dropna(subset=A.ALL3).reset_index(drop=True); mine = A.icc_a1(m[A.ALL3].values)
    try:
        import pingouin as pg
    except ImportError:
        print(f'ICC(A,1) {mine:.4f}: pingouin not installed, check skipped (pip install pingouin)'); return 0 if ok else 1
    L = m.reset_index().melt(id_vars='index', value_vars=A.ALL3, var_name='device', value_name='hr')
    t = pg.intraclass_corr(data=L, targets='index', raters='device', ratings='hr')
    row = t[t.Type.isin(['ICC(A,1)', 'ICC2'])].iloc[0]; good = abs(mine - row.ICC) < tol_icc; ok &= good
    print(f'{"All three (ICC)":18s} ICC(A,1) {mine:.4f} (pingouin {row.ICC:.4f}, {row.Type})  -> {"OK" if good else "MISMATCH"}')
    print('\nAll checks passed.' if ok else '\nSome checks FAILED.'); return 0 if ok else 1

if __name__ == '__main__':
    sys.exit(main())
